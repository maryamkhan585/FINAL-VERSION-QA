/**
 * Appium Mobile Web Test Code Generator
 * Generates custom mobile browser automation scripts using WebdriverIO and Appium.
 */

function generateAppiumScript(targetUrl) {
    let rawInput = (targetUrl || '').trim().replace(/^["']|["']$/g, '');
    const isApk = /\.apk$/i.test(rawInput) || /^[a-zA-Z]:\\.*\.apk$/i.test(rawInput);
    
    let domain = rawInput.split(/[\\/]/).pop() || 'example.com';
    let cleanUrl = rawInput.replace(/'/g, "\\'").replace(/\\/g, '\\\\');

    // Analyze target portal type
    let portalProfile;
    if (typeof analyzeTargetPortal === 'function') {
        portalProfile = analyzeTargetPortal(rawInput);
    } else if (typeof require !== 'undefined') {
        try {
            const { analyzeTargetPortal: analyzer } = require('./domain-analyzer');
            portalProfile = analyzer(rawInput);
        } catch(e) {}
    }

    if (!portalProfile) {
        portalProfile = { category: isApk ? "Android Native Application (.apk)" : "Enterprise Web Service" };
    }

    const appCapability = isApk 
        ? `'appium:app': '${cleanUrl}',\n        'appium:appPackage': 'com.example.app',\n        'appium:appActivity': '.MainActivity',`
        : `browserName: 'Chrome',\n        'appium:chromedriverExecutableDir': '/path/to/chromedriver/binaries',`;

    return `const { remote } = require('webdriverio');
const assert = require('assert');

/**
 * Automated Appium Mobile Test Suite for ${domain}
 * Interface Classification: ${portalProfile.category}
 * Framework: WebdriverIO (v8) Client
 * Generated by Antigravity Automated Testing Platform.
 */

// 1. Appium Server Connection & Device Capabilities Configuration
const appiumOptions = {
    hostname: '127.0.0.1',
    port: 4723,
    path: '/wd/hub',
    capabilities: {
        platformName: 'Android',
        'appium:platformVersion': '13.0',
        'appium:deviceName': 'Android Emulator',
        'appium:automationName': 'UiAutomator2',
        ${appCapability}
        'appium:newCommandTimeout': 240
    }
};

async function runMobileAudit() {
    console.log('Connecting to Appium Server at http://127.0.0.1:4723/wd/hub...');
    const client = await remote(appiumOptions);
    
    try {
        console.log('Launching mobile browser on emulator/device...');
        
        // Step 1: Navigate to target URL
        console.log('Navigating to target URL: ${cleanUrl}');
        await client.url('${cleanUrl}');
        
        // Wait for page body to load
        const body = await client.$('body');
        await body.waitForDisplayed({ timeout: 15000 });
        
        // Assert: Verify page title
        const title = await client.getTitle();
        console.log(\`Captured Mobile Page Title: "\${title}"\`);
        assert.ok(title, 'Title should be set and non-empty');
        
        // Step 2: Device Screen & Viewport Audit
        const screenDimensions = await client.getWindowSize();
        console.log(\`Mobile Device Screen Size: \${screenDimensions.width}x\${screenDimensions.height}\`);
        
        // Step 3: Touch Target Accessibility Verification (WCAG 2.1 compliance check)
        // Checks that touch-interactive components are at least 48x48px for finger taps
        console.log('Auditing interactive button sizes for touch compliance...');
        const buttons = await client.$$('button, a.btn, input[type="submit"]');
        let complianceWarnings = 0;
        
        for (let i = 0; i < Math.min(buttons.length, 5); i++) {
            const btn = buttons[i];
            const size = await btn.getSize();
            const tag = await btn.getTagName();
            const text = await btn.getText();
            
            console.log(\`Interactive Target #\${i+1} [\${tag}]: size=\${size.width}x\${size.height}px, text="\${text}"\`);
            
            if (size.width < 44 || size.height < 44) {
                console.log(\`[WARNING] Touch target accessibility issue: Element "\${text}" is too small (\${size.width}x\${size.height}px). Minimum recommended is 44x44px.\`);
                complianceWarnings++;
            }
        }
        
        // Step 4: Mobile Menu Drawer Interaction Audit
        // Mobile menus are typically hidden behind burger bars. Let's find and test common selectors.
        console.log('Searching for typical mobile navigation menu buttons...');
        const menuSelectors = [
            '.menu-toggle', '.hamburger', '#menu-button', '[aria-label="menu"]',
            'header button', '.nav-toggle', 'a[href="#menu"]'
        ];
        
        let menuButton = null;
        for (const selector of menuSelectors) {
            const el = await client.$(selector);
            if (await el.isExisting() && await el.isDisplayed()) {
                menuButton = el;
                console.log(\`Mobile navigation trigger found using selector: "\${selector}"\`);
                break;
            }
        }
        
        if (menuButton) {
            console.log('Tapping mobile menu burger button...');
            await menuButton.click();
            await client.pause(1000); // Wait for transition animation
            
            // Check if navigation drawer became visible
            const mobileNav = await client.$('nav, .nav-menu, #menu, .menu-panel');
            if (await mobileNav.isExisting()) {
                const isShown = await mobileNav.isDisplayed();
                console.log(\`Mobile navigation drawer visible after tap: \${isShown ? 'Yes' : 'No'}\`);
            }
            
            // Tap again to close
            await menuButton.click();
            await client.pause(1000);
        } else {
            console.log('No standard mobile menu button detected. Skipping drawer test.');
        }

        // Step 5: Screen Capture for Artifact Logs
        console.log('Taking mobile web screenshot...');
        const screenshot = await client.takeScreenshot();
        require('fs').writeFileSync('./mobile_audit_screenshot.png', screenshot, 'base64');
        console.log('Mobile screenshot saved to "./mobile_audit_screenshot.png" successfully.');
        
        console.log('Mobile Web Appium Audit completed successfully.');
    } catch (error) {
        console.error('Appium mobile test execution failed:', error);
        throw error;
    } finally {
        // Always tear down the session
        console.log('Terminating mobile web session and cleaning up Appium driver...');
        await client.deleteSession();
    }
}

// Execute test suite if run directly
if (require.main === module) {
    runMobileAudit();
} else {
    module.exports = { runMobileAudit };
}
`;
}

// Export function if running in Node, otherwise bind to window for browser use
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { generateAppiumScript };
} else {
    window.generateAppiumScript = generateAppiumScript;
}
